// Exercise production policies without launching ArkUI or a VPN.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.resolve(__dirname, '../../..');
const pin = JSON.parse(fs.readFileSync(path.join(root, 'apps/harmonyos/toolchains.json')));
const cli = path.join(process.env.HOME, '.local/opt/harmonyos/command-line-tools', pin[process.platform === 'linux' ? 'linuxCli' : 'cli'].version);
const ts = require(path.join(cli, 'hvigor/hvigor/node_modules/typescript'));
let systemLanguage = 'zh-Hans';
function load(relative) {
  const source = fs.readFileSync(path.join(root, 'apps/harmonyos/entry/src/main/ets', relative), 'utf8');
  const code = ts.transpileModule(source, {compilerOptions: {module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020}}).outputText;
  const sandbox = {exports: {}, require: name => { if (name === '@kit.PerformanceAnalysisKit') return {hilog: {warn() {}}}; if (name === '@kit.LocalizationKit') return {i18n: {System: {getSystemLanguage: () => systemLanguage}}}; if (name === './Messages') return load('platform/Messages.ets'); throw new Error('Unexpected runtime import: '+name); }}; vm.runInNewContext(code, sandbox); return sandbox.exports;
}
(async () => {
  const {failureMessage, dnsStateName} = load('platform/FailureMessages.ets');
  const invalidPassword = {code: 'AUTH_REQUIRED', operation: 'native_session.authenticate', message: 'fnOS username or password is invalid'};
  assert.equal(failureMessage(invalidPassword), '用户名或密码无效，请重试。');
  assert.equal(dnsStateName('ready'), '就绪');
  assert.equal(failureMessage({code: 'AUTH_REQUIRED', operation: 'native_session.authenticate', message: 'fnOS session token was rejected'}), '请重新登录后重试。', 'expired sessions must not be described as wrong passwords');
  assert.equal(failureMessage({code: 'INVALID_ARGUMENT', message: 'invalid FN ID'}), 'FN Connect ID 格式不正确');
  systemLanguage = 'en-US';
  assert.equal(failureMessage(invalidPassword), 'The username or password is incorrect. Try again.');
  assert.equal(dnsStateName('ready'), 'Ready');
  assert.equal(failureMessage({code: 'AUTH_REQUIRED', remoteCode: 'TWO_FACTOR_REQUIRED', message: 'raw'}), 'This account requires two-factor authentication. Enter your OTP.');
  assert.match(failureMessage({code: 'TIMEOUT', operation: 'native_session.connect', message: 'raw'}), /FN Connect ID/);
  assert.equal(invalidPassword.message, 'fnOS username or password is invalid', 'localization preserves original diagnostic data');
  const {tr} = load('platform/Messages.ets');
  for (const label of ['打开目录', '正在复制…', '应用内调试', '连接服务暂不可用，请在主窗口重新连接']) assert.doesNotMatch(tr(label), /[\u4e00-\u9fff]/);
  systemLanguage = 'zh-Hans';
  const {configureWindow} = load('platform/WindowStartup.ets');
  const attempted = [];
  const unsupported = name => () => { attempted.push(name); throw {code: 801, message: 'unsupported window mode'}; };
  await configureWindow({setWindowLayoutFullScreen: unsupported('layout'), setWindowDecorVisible: unsupported('decorations'),
    setWindowTitle: unsupported('title'), setWindowLimits: unsupported('limits')}, true, 'FnCPN', 360);
  assert.deepEqual(attempted, ['layout', 'decorations', 'title', 'limits'], 'unsupported settings neither abort setup nor skip remaining settings');
  attempted.length = 0;
  await configureWindow({setWindowLayoutFullScreen: unsupported('layout')}, false, 'FnCPN', 360);
  assert.deepEqual(attempted, ['layout'], 'mobile does not call desktop-only window APIs');
  const {initialLoginPage} = load('controller/LoginPolicy.ets');
  assert.equal(initialLoginPage('RECONNECTING', ''), true, 'failed first login must retain login form');
  assert.equal(initialLoginPage('ERROR', ''), true);
  assert.equal(initialLoginPage('RECONNECTING', 'existing-nas'), false, 'existing session reconnect is a main-page state');
  assert.equal(initialLoginPage('AUTH_REQUIRED', 'existing-nas'), true);
  assert.equal(initialLoginPage('RELAY', 'existing-nas'), false);
  const {resolveLayout, vpnAvailability, loginColumns} = load('controller/LayoutPolicy.ets');
  assert.equal(loginColumns(639, 1), false);
  assert.equal(loginColumns(640, 1), true);
  assert.equal(loginColumns(768, 1), true, 'wide foldable login fits side by side');
  assert.equal(loginColumns(768, 1.5), false, 'large type retains readable form');
  assert.equal(loginColumns(584, 1), false, 'sidebar reduces usable form area');
  for (const width of [320, 599, 600, 700, 839]) assert.equal(resolveLayout(width, 800, 1, false, false).embedded, false);
  assert.equal(resolveLayout(840, 800, 1, false, false).embedded, true);
  assert.equal(resolveLayout(1000, 800, 2, false, false).embedded, false, 'large text retains content width');
  assert.equal(resolveLayout(1200, 800, 1, false, true).embedded, false, 'user sidebar preference');
  assert.equal(resolveLayout(1600, 800, 1, false, false).twoColumns, true);
  assert.equal(resolveLayout(840, 800, 1, false, false).twoColumns, false, 'use remaining content width');
  assert.equal(resolveLayout(700, 400, 1, false, false).compactHeight, true);
  assert.equal(resolveLayout(1280, 720, 1, true, true).embedded, true, 'TV navigation needs no swipe');
  assert.notEqual(vpnAvailability('tv', 25, true, false), '');
  assert.equal(vpnAvailability('tv', 26, true, false), '');
  assert.notEqual(vpnAvailability('2in1', 20, false, false), '');
  assert.equal(vpnAvailability('phone', 20, true, false), '');
  assert.equal(vpnAvailability('phone', 20, false, true), '');
  const {AdminWindows} = load('controller/AdminWindows.ets');
  let closes = 0; AdminWindows.register(() => closes++); AdminWindows.invalidate(); AdminWindows.invalidate(); assert.equal(closes, 1);
  const launches = []; const context = {startAbility: async want => launches.push(want)};
  await assert.rejects(() => AdminWindows.open(context, 'https://example.com', '/private', 'test|user'));
  assert.equal(launches.length, 0);
  await AdminWindows.open(context, 'http://127.0.0.1:12345/', '/private', 'test|user');
  assert.equal(launches[0].abilityName, 'AdminAbility');
  assert.equal(launches[0].parameters.identity, 'test|user');
  console.log('Adaptive layout, VPN capability and admin window policy checks passed');
})().catch(error => {console.error(error);process.exitCode = 1;});
